static inline void MjkFont_DrawChar(uint32_t* fb, int x, int y, char c, uint32_t color, int scale) {
    if (!fb || scale <= 0) return;
    char up = (char)toupper((unsigned char)c);
    if (up < 32 || up > 93) up = ' ';
    const uint8_t* glyph = g_mjk_font_glyphs[up - 32];

    for (int row = 0; row < 8; ++row) {
        uint8_t byte = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if ((byte >> (7 - col)) & 1) {
                for (int sy = 0; sy < scale; ++sy) {
                    for (int sx = 0; sx < scale; ++sx) {
                        int px = x + col * scale + sx;
                        int py = y + row * scale + sy;
                        if (px >= 0 && px < MJK_SCREEN_WIDTH && py >= 0 && py < MJK_SCREEN_HEIGHT) {
                            fb[py * MJK_SCREEN_WIDTH + px] = color;
                        }
                    }
                }
            }
        }
    }
}

static inline void MjkFont_DrawString(uint32_t* fb, int x, int y, const char* str, uint32_t color, int scale) {
    if (!fb || !str) return;
    int cur_x = x;
    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            y += 9 * scale;
        } else {
            MjkFont_DrawChar(fb, cur_x, y, *str, color, scale);
            cur_x += 8 * scale;
        }
        str++;
    }
}

