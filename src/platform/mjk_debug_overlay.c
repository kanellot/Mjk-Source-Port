static void blend_rect(uint32_t* fb, int x, int y, int w, int h) {
    for (int py = y; py < y + h; ++py) {
        if (py < 0 || py >= MJK_SCREEN_HEIGHT) {
            continue;
        }
        for (int px = x; px < x + w; ++px) {
            if (px < 0 || px >= MJK_SCREEN_WIDTH) {
                continue;
            }
            uint32_t c = fb[py * MJK_SCREEN_WIDTH + px];
            uint32_t r = ((c >> 16u) & 0xFFu) >> 1u;
            uint32_t g = ((c >> 8u) & 0xFFu) >> 1u;
            uint32_t b = (c & 0xFFu) >> 1u;
            fb[py * MJK_SCREEN_WIDTH + px] = 0xFF000000u | (r << 16u) | (g << 8u) | b;
        }
    }
}

static void draw_box_outline(uint32_t* fb, int x, int y, int w, int h, uint32_t color) {
    for (int px = x; px < x + w; ++px) {
        if (px >= 0 && px < MJK_SCREEN_WIDTH) {
            if (y >= 0 && y < MJK_SCREEN_HEIGHT) {
                fb[y * MJK_SCREEN_WIDTH + px] = color;
            }
            if (y + h - 1 >= 0 && y + h - 1 < MJK_SCREEN_HEIGHT) {
                fb[(y + h - 1) * MJK_SCREEN_WIDTH + px] = color;
            }
        }
    }
    for (int py = y; py < y + h; ++py) {
        if (py >= 0 && py < MJK_SCREEN_HEIGHT) {
            if (x >= 0 && x < MJK_SCREEN_WIDTH) {
                fb[py * MJK_SCREEN_WIDTH + x] = color;
            }
            if (x + w - 1 >= 0 && x + w - 1 < MJK_SCREEN_WIDTH) {
                fb[py * MJK_SCREEN_WIDTH + (x + w - 1)] = color;
            }
        }
    }
}

static void draw_text(uint32_t* fb, int x, int y, const char* text, uint32_t color) {
    if (!fb || !text) {
        return;
    }
    int cx = x;
    for (size_t i = 0u; text[i] != '\0'; ++i) {
        unsigned char ch = (unsigned char)text[i];
        if (ch >= 'a' && ch <= 'z') {
            ch = (unsigned char)(ch - ('a' - 'A'));
        }
        if (ch < 0x20u || ch > 0x5Fu) {
            ch = '?';
        }
        const uint8_t* glyph = k_font_5x7[ch - 0x20u];
        for (int row = 0; row < 7; ++row) {
            int py = y + row;
            if (py < 0 || py >= MJK_SCREEN_HEIGHT) {
                continue;
            }
            uint8_t bits = glyph[row];
            for (int col = 0; col < 5; ++col) {
                int px = cx + col;
                if (px >= 0 && px < MJK_SCREEN_WIDTH && ((bits >> (4 - col)) & 1u) != 0u) {
                    fb[py * MJK_SCREEN_WIDTH + px] = color;
                }
            }
        }
        cx += 6;
    }
}

static const char* room_tag(uint8_t room_id) {
    switch (room_id) {
        case 0x00u: return "TITLE";
        case 0x01u: return "R1-1";
        case 0x90u: return "BOMB1";
        case 0xACu: return "TORTURE";
        case 0xA0u: return "END0";
        case 0xA1u: return "END1";
        case 0xA2u: return "END2";
        case 0xA3u: return "END3";
        default:    return (room_id >= 0x90u && room_id <= 0x9Fu) ? "BOMB" : "ROOM";
    }
}

void MjkDebugOverlay_Init(MjkDebugOverlayState* st) {
    if (!st) {
        return;
    }
    memset(st, 0, sizeof(*st));
    st->warp_room_id = 0x01u;
}

bool MjkDebugOverlay_HandleKeys(MjkDebugOverlayState* st,
                                uint32_t debug_keys,
                                uint8_t* out_warp_target) {
    if (!st) {
        return false;
    }
    if ((debug_keys & MJK_DBG_TOGGLE_OVERLAY) != 0u) {
        st->show_telemetry = !st->show_telemetry;
    }
    if ((debug_keys & MJK_DBG_TOGGLE_WARP) != 0u) {
        st->show_warp = !st->show_warp;
    }
    if ((debug_keys & MJK_DBG_CYCLE_CHEATS) != 0u) {
        st->cheat_mode = (uint8_t)((st->cheat_mode + 1u) % 3u);
    }
    if ((debug_keys & MJK_DBG_TOGGLE_PAUSE) != 0u) {
        st->paused = !st->paused;
    }
    if ((debug_keys & MJK_DBG_STEP_FRAME) != 0u && st->paused) {
        st->step_requested = true;
    }
    if ((debug_keys & MJK_DBG_WARP_PREV) != 0u) {
        st->warp_room_id = (uint8_t)(st->warp_room_id - 1u);
    }
    if ((debug_keys & MJK_DBG_WARP_NEXT) != 0u) {
        st->warp_room_id = (uint8_t)(st->warp_room_id + 1u);
    }
    if ((debug_keys & MJK_DBG_WARP_CONFIRM) != 0u) {
        if (out_warp_target) {
            *out_warp_target = st->warp_room_id;
        }
        return true;
    }
    return false;
}

void MjkDebugOverlay_Render(const MjkDebugOverlayState* st,
                            const MjkDebugTelemetry* tel,
                            uint32_t* fb_argb8888) {
    if (!st || !fb_argb8888) {
        return;
    }

    if (st->show_telemetry && tel) {
        static const char* const k_cheats[3] = { "OFF", "INV", "M3" };
        char line1[64];
        snprintf(line1, sizeof(line1), "RM:$%02X ST:%02X LV:%u M:%u T:%02X",
                 tel->room_id, tel->game_state, tel->lives, tel->mighty_level, tel->timer_bcd);
        char line2[64];
        snprintf(line2, sizeof(line2), "CAM:%3u OAM:%2u CHT:%s",
                 (unsigned)tel->camera_x, (unsigned)tel->oam_count, k_cheats[st->cheat_mode % 3u]);

        blend_rect(fb_argb8888, 2, 2, 252, 20);
        draw_text(fb_argb8888, 5, 4, line1, 0xFFFCFCFCu);
        draw_text(fb_argb8888, 5, 13, line2, 0xFF88D800u);

        if (tel->has_jack) {
            draw_box_outline(fb_argb8888, tel->jack_x - 8, tel->jack_y - 8, 16, 16, 0xFF5CE430u);
        }
    }

    if (st->show_warp) {
        char wline[64];
        snprintf(wline, sizeof(wline), "WARP: $%02X (%s) [/] F6=GO",
                 st->warp_room_id, room_tag(st->warp_room_id));
        blend_rect(fb_argb8888, 2, 218, 252, 18);
        draw_box_outline(fb_argb8888, 2, 218, 252, 18, 0xFFFCA044u);
        draw_text(fb_argb8888, 6, 224, wline, 0xFFFCA044u);
    }

    if (st->paused) {
        blend_rect(fb_argb8888, 92, 24, 72, 11);
        draw_text(fb_argb8888, 96, 26, "[PAUSED]", 0xFFFE8170u);
    }
}
