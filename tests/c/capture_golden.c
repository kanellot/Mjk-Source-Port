/**
 * @file capture_golden.c
 * @brief Capturador temporal de Golden Vectors desde el motor original (Ticket R-01).
 *
 * Genera `tests/c/golden_reference.h` con hashes FNV-1a y trayectorias numéricas
 * de comportamiento (cero bytes propietarios de la ROM). Este archivo se elimina en R-17.
 */

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "mjk_assets.h"
#include "mjk_doors.h"
#include "mjk_game.h"
#include "mjk_player.h"
#include "mjk_rom_extractor.h"
#include "mjk_room_decoder.h"

static uint32_t fnv1a_32(const void* data, size_t len) {
    const uint8_t* p = (const uint8_t*)data;
    uint32_t h = 2166136261u;
    for (size_t i = 0u; i < len; ++i) {
        h ^= (uint32_t)p[i];
        h *= 16777619u;
    }
    return h;
}

static bool load_rom_assets(MjkAssetPackage* out_pkg) {
    char rom_path[512];
    snprintf(rom_path, sizeof(rom_path), "%s/asm/bin/mbj-us.nes", MJK_SOURCE_DIR);
    FILE* f = fopen(rom_path, "rb");
    if (!f) {
        fprintf(stderr, "[ERROR] No se pudo abrir %s\n", rom_path);
        return false;
    }
    uint8_t* rom = (uint8_t*)malloc(MJK_ROM_EXPECTED_SIZE);
    if (!rom) {
        fclose(f);
        return false;
    }
    size_t got = fread(rom, 1u, MJK_ROM_EXPECTED_SIZE, f);
    fclose(f);
    if (got != MJK_ROM_EXPECTED_SIZE) {
        free(rom);
        return false;
    }
    uint8_t* v2_buf = NULL;
    size_t v2_size = 0u;
    char sha1_hex[MJK_SHA1_HEX_LEN + 1u];
    MjkAssetError err = MjkRom_BuildAssetsV2Buffer(rom, MJK_ROM_EXPECTED_SIZE, &v2_buf, &v2_size, sha1_hex);
    free(rom);
    if (err != MJK_ASSET_OK) {
        free(v2_buf);
        return false;
    }
    err = MjkAssets_LoadFromMemory(v2_buf, v2_size, out_pkg);
    free(v2_buf);
    return (err == MJK_ASSET_OK);
}

static void capture_jump_traj(const MjkAssetPackage* pkg,
                              uint8_t first_btn,
                              uint8_t hold_btn,
                              int flutter_frame,
                              int frames,
                              int16_t* out_x,
                              int16_t* out_y,
                              uint8_t* out_air) {
    MjkRoomState room;
    memset(&room, 0, sizeof(room));
    for (int mx = 0; mx < 16; ++mx) {
        room.static_metatiles[12][mx] = 0x01u;
    }
    MjkPlayer p;
    MjkPlayer_Init(&p, 128u, 184u);
    MjkInputState in;
    memset(&in, 0, sizeof(in));

    for (int f = 0; f < frames; ++f) {
        uint8_t btn = hold_btn;
        if (f == 0) {
            btn = first_btn;
        } else if (flutter_frame > 0 && f == flutter_frame) {
            btn = (uint8_t)(hold_btn | MJK_BTN_A);
        }
        MjkInput_Update(&in, btn);
        MjkSoundId sfx = MJK_SND_SILENCE;
        bool add10 = false;
        MjkPlayer_Update(&p, &in, pkg, &room, NULL, MJK_RF_SINGLE_SCREEN,
                         0u, 0u, false, NULL, NULL, NULL, &sfx, &add10);
        if (out_x) { out_x[f] = (int16_t)MjkUQ8_Int(p.pos_x); }
        if (out_y) { out_y[f] = (int16_t)MjkUQ8_Int(p.pos_y); }
        if (out_air) { out_air[f] = p.in_air ? 1u : 0u; }
    }
}

static void step_game_n(MjkGame* g, uint8_t btn, int n) {
    MjkInputState in;
    memset(&in, 0, sizeof(in));
    for (int i = 0; i < n; ++i) {
        MjkInput_Update(&in, btn);
        MjkGame_StepFrame(g, &in);
    }
}

int main(void) {
    MjkAssetPackage pkg;
    if (!load_rom_assets(&pkg)) {
        return 1;
    }

    char out_path[512];
    snprintf(out_path, sizeof(out_path), "%s/tests/c/golden_reference.h", MJK_SOURCE_DIR);
    FILE* out = fopen(out_path, "w");
    if (!out) {
        fprintf(stderr, "[ERROR] No se pudo crear %s\n", out_path);
        MjkAssets_Unload(&pkg);
        return 1;
    }

    fprintf(out, "/* AUTO-GENERATED by capture_golden (R-01) from verified legacy engine.\n");
    fprintf(out, " * Contains ONLY behavioral hashes and numeric trajectories (zero ROM bytes).\n");
    fprintf(out, " */\n");
    fprintf(out, "#ifndef MJK_GOLDEN_REFERENCE_H\n");
    fprintf(out, "#define MJK_GOLDEN_REFERENCE_H\n\n");
    fprintf(out, "#include <stdint.h>\n\n");

    /* 1. 256 Rooms geometry + object metadata hashes */
    fprintf(out, "typedef struct {\n");
    fprintf(out, "    uint32_t pure_mt_hash;\n");
    fprintf(out, "    uint32_t static_mt_hash;\n");
    fprintf(out, "    uint32_t objects_hash;\n");
    fprintf(out, "    uint8_t  palette_set;\n");
    fprintf(out, "    uint8_t  music_id;\n");
    fprintf(out, "    uint8_t  section_id;\n");
    fprintf(out, "    uint8_t  is_horizontal;\n");
    fprintf(out, "    uint8_t  is_bomb_room;\n");
    fprintf(out, "    uint8_t  object_count;\n");
    fprintf(out, "} GoldenRoomRef;\n\n");
    fprintf(out, "static const GoldenRoomRef k_golden_rooms[256] = {\n");

    MjkRoomPersistRam persist;
    for (int r = 0; r < 256; ++r) {
        MjkRoomState room;
        memset(&room, 0, sizeof(room));
        memset(&persist, 0, sizeof(persist));
        MjkRoom_DecodeGeometry(&pkg, (uint8_t)r, &room);
        uint32_t pure_mt_hash = fnv1a_32(room.static_metatiles, sizeof(room.static_metatiles));
        if (r > 0) {
            MjkRoom_PreloadSection(&pkg, (uint8_t)r, &persist, 0u);
            MjkRoom_DecodeObjects(&pkg, (uint8_t)r, &persist, &room);
        }
        uint32_t mt_hash = fnv1a_32(room.static_metatiles, sizeof(room.static_metatiles));
        uint8_t obj_pack[MJK_ROOM_MAX_OBJECTS * 5u];
        for (uint8_t i = 0u; i < room.object_count; ++i) {
            obj_pack[i * 5u + 0u] = room.objects[i].opcode;
            obj_pack[i * 5u + 1u] = room.objects[i].yx;
            obj_pack[i * 5u + 2u] = room.objects[i].yx2;
            obj_pack[i * 5u + 3u] = room.objects[i].extra;
            obj_pack[i * 5u + 4u] = room.objects[i].ram_state;
        }
        uint32_t obj_hash = fnv1a_32(obj_pack, (size_t)room.object_count * 5u);
        fprintf(out, "    { 0x%08Xu, 0x%08Xu, 0x%08Xu, %uu, %uu, %uu, %uu, %uu, %uu }%s\n",
                pure_mt_hash, mt_hash, obj_hash,
                (unsigned)room.palette_set, (unsigned)room.music_id,
                (unsigned)room.section_id, room.is_horizontal ? 1u : 0u,
                room.is_bomb_room ? 1u : 0u, (unsigned)room.object_count,
                (r == 255) ? "" : ",");
    }
    fprintf(out, "};\n\n");

    /* 2. Jack Physics Trajectories (60 frames each) */
    int16_t y_neutral[60], y_low[60], y_high[60], y_flutter[60], x_right[30], y_right[30];
    uint8_t air_neutral[60];
    capture_jump_traj(&pkg, MJK_BTN_A, 0u, -1, 60, NULL, y_neutral, air_neutral);
    capture_jump_traj(&pkg, (uint8_t)(MJK_BTN_A | MJK_BTN_DOWN), MJK_BTN_DOWN, -1, 60, NULL, y_low, NULL);
    capture_jump_traj(&pkg, (uint8_t)(MJK_BTN_A | MJK_BTN_UP), MJK_BTN_UP, -1, 60, NULL, y_high, NULL);
    capture_jump_traj(&pkg, MJK_BTN_A, 0u, 16, 60, NULL, y_flutter, NULL);
    capture_jump_traj(&pkg, (uint8_t)(MJK_BTN_A | MJK_BTN_RIGHT), MJK_BTN_RIGHT, -1, 30, x_right, y_right, NULL);

    fprintf(out, "static const int16_t k_golden_jump_neutral_y[60] = {\n    ");
    for (int i = 0; i < 60; ++i) {
        fprintf(out, "%d%s%s", (int)y_neutral[i], (i == 59) ? "" : ",", ((i + 1) % 12 == 0 && i != 59) ? "\n    " : " ");
    }
    fprintf(out, "\n};\n\n");

    fprintf(out, "static const uint8_t k_golden_jump_neutral_air[60] = {\n    ");
    for (int i = 0; i < 60; ++i) {
        fprintf(out, "%u%s%s", (unsigned)air_neutral[i], (i == 59) ? "" : ",", ((i + 1) % 15 == 0 && i != 59) ? "\n    " : " ");
    }
    fprintf(out, "\n};\n\n");

    fprintf(out, "static const int16_t k_golden_jump_low_y[60] = {\n    ");
    for (int i = 0; i < 60; ++i) {
        fprintf(out, "%d%s%s", (int)y_low[i], (i == 59) ? "" : ",", ((i + 1) % 12 == 0 && i != 59) ? "\n    " : " ");
    }
    fprintf(out, "\n};\n\n");

    fprintf(out, "static const int16_t k_golden_jump_high_y[60] = {\n    ");
    for (int i = 0; i < 60; ++i) {
        fprintf(out, "%d%s%s", (int)y_high[i], (i == 59) ? "" : ",", ((i + 1) % 12 == 0 && i != 59) ? "\n    " : " ");
    }
    fprintf(out, "\n};\n\n");

    fprintf(out, "static const int16_t k_golden_jump_flutter_y[60] = {\n    ");
    for (int i = 0; i < 60; ++i) {
        fprintf(out, "%d%s%s", (int)y_flutter[i], (i == 59) ? "" : ",", ((i + 1) % 12 == 0 && i != 59) ? "\n    " : " ");
    }
    fprintf(out, "\n};\n\n");

    fprintf(out, "static const int16_t k_golden_jump_right_x[30] = {\n    ");
    for (int i = 0; i < 30; ++i) {
        fprintf(out, "%d%s%s", (int)x_right[i], (i == 29) ? "" : ",", ((i + 1) % 10 == 0 && i != 29) ? "\n    " : " ");
    }
    fprintf(out, "\n};\n\n");

    fprintf(out, "static const int16_t k_golden_jump_right_y[30] = {\n    ");
    for (int i = 0; i < 30; ++i) {
        fprintf(out, "%d%s%s", (int)y_right[i], (i == 29) ? "" : ",", ((i + 1) % 10 == 0 && i != 29) ? "\n    " : " ");
    }
    fprintf(out, "\n};\n\n");

    /* 3. Renderer Golden Frame Hashes */
    static MjkGame g;
    static uint32_t fb[MJK_SCREEN_WIDTH * MJK_SCREEN_HEIGHT];

    MjkGame_Init(&g, &pkg);
    step_game_n(&g, 0u, 10);
    MjkGame_Render(&g, fb);
    uint32_t h_copyright = fnv1a_32(fb, sizeof(fb));

    step_game_n(&g, MJK_BTN_START, 3);
    step_game_n(&g, 0u, 12);
    MjkGame_Render(&g, fb);
    uint32_t h_title = fnv1a_32(fb, sizeof(fb));

    step_game_n(&g, MJK_BTN_START, 3);
    step_game_n(&g, 0u, 370);
    MjkGame_Render(&g, fb);
    uint32_t h_room1 = fnv1a_32(fb, sizeof(fb));

    MjkGame_WarpToRoom(&g, 0x90u);
    step_game_n(&g, 0u, 30);
    MjkGame_Render(&g, fb);
    uint32_t h_bomb90 = fnv1a_32(fb, sizeof(fb));

    MjkGame_WarpToRoom(&g, 0xACu);
    step_game_n(&g, 0u, 30);
    MjkGame_Render(&g, fb);
    uint32_t h_torture = fnv1a_32(fb, sizeof(fb));

    fprintf(out, "#define MJK_GOLDEN_FRAME_COPYRIGHT 0x%08Xu\n", h_copyright);
    fprintf(out, "#define MJK_GOLDEN_FRAME_TITLE     0x%08Xu\n", h_title);
    fprintf(out, "#define MJK_GOLDEN_FRAME_ROOM1     0x%08Xu\n", h_room1);
    fprintf(out, "#define MJK_GOLDEN_FRAME_BOMB90    0x%08Xu\n", h_bomb90);
    fprintf(out, "#define MJK_GOLDEN_FRAME_TORTURE   0x%08Xu\n\n", h_torture);

    fprintf(out, "#endif /* MJK_GOLDEN_REFERENCE_H */\n");
    fclose(out);
    MjkAssets_Unload(&pkg);
    printf("[OK] Generado %s\n", out_path);
    return 0;
}
